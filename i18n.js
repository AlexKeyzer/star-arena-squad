  let currentLang = 'ru'; // Русский язык по умолчанию

  function detectInitialLang(searchStr) {
    const q = typeof searchStr === 'string'
      ? searchStr
      : (typeof location !== 'undefined' ? location.search : '');
    try {
      const params = new URLSearchParams(q);
      const raw = (params.get('lang') || params.get('vk_language') || '').toLowerCase();
      if (raw.startsWith('en') || raw === '3') return 'en';
      if (raw.startsWith('ru') || raw === '0') return 'ru';
    } catch (_) {
      // Ignore malformed query
    }
    return 'ru';
  }

  function setLang(lang) {
    currentLang = lang === 'ru' ? 'ru' : 'en';
    return currentLang;
  }

  function getLang() {
    return currentLang;
  }

  function t(key, vars) {
    const table = DICT[currentLang] || DICT.en;
    let str = table[key] !== undefined ? table[key] : (DICT.en[key] !== undefined ? DICT.en[key] : key);
    if (vars && typeof str === 'string') {
      for (const [k, v] of Object.entries(vars)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
    return str;
  }

  function pick(obj, baseField) {
    if (!obj) return '';
    const suffix = currentLang === 'ru' ? 'Ru' : 'En';
    return obj[baseField + suffix] !== undefined ? obj[baseField + suffix] : (obj[baseField + 'En'] || '');
  }

  const api = { DICT, detectInitialLang, setLang, getLang, t, pick };

  if (typeof module !== 'undefined' && module.exports) {
    module.exports = api;
  }
  root.SA = root.SA || {};
  root.SA.i18n = api;
